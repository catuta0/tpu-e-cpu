#!/usr/bin/env python3
"""Generate the K / ACT_SHIFT sweep vectors for tests/tpu/tb_sc_tpu.v (task RTL-TPU).

Why
---
The SW-01a vector files (sim/data/, see sim/data/README.md) cover K = 8 (360
images), K = 4 and K = 10 (16 images) and the corner sets (K = 4). REQ-TPU-013 (b)
asks for >= 3 images x every K in 4..10 x RNG_MODE 0/1/2 x ACT_SHIFT 0/3/7, and
REQ-TPU-014 for CYCLES at every K. This script fills that gap.

How (no new model code: the expected values come from the project golden model)
---
* parameter set 0: ``sim/data/weights.hex`` + ``sim/data/bias.hex`` (SW-01a);
* images: the INPUT words of the first 3 vectors of
  ``sim/data/tpu_vectors_mode1.txt`` (test positions 0, 1, 2);
* expected HIDDEN/SCORE/RESULT: ``code/python/sctpu/model.py``
  ``sc_inference_reference`` (the slow literal transcription of spec 5.3, LFSRs
  stepped one step at a time) AND ``sc_inference`` (fast exact path); the
  script aborts if the two disagree on any field;
* line format: ``code/python/sctpu/gen_hex.py`` ``vector_line`` (43 hex fields).

Output: ``sim/tpu/vectors/tpu_vectors_sweep_mode{0,1,2}.txt`` (one file per mode,
3 images x 7 K x 3 s = 63 vectors each). The golden model is only imported, never
modified (it belongs to the software-engineer).

Usage (from the project root):
    .venv/bin/python tests/tpu/gen_tpu_sweep_vectors.py
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "code" / "python"))

from sctpu import model as M          # noqa: E402  (golden model, read-only use)
from sctpu import gen_hex as G        # noqa: E402  (vector line formatter)

DATA = ROOT / "sim" / "data"
OUT = ROOT / "sim" / "tpu" / "vectors"
K_LIST = range(4, 11)                 # every legal K
S_LIST = (0, 3, 7)                    # ACT_SHIFT values of REQ-TPU-013 (b)
N_IMG = 3                             # images (test positions 0..2)


def read_hex(path: Path) -> list[int]:
    """Read a $readmemh file (one hex word per line) into a list of ints."""
    return [int(t, 16) for t in path.read_text().split()]


def main() -> int:
    """Generate the three sweep files; return 0 on success."""
    words = read_hex(DATA / "weights.hex")
    ram = M.words_to_bytes(words)
    biases = [v - 65536 if v & 0x8000 else v for v in read_hex(DATA / "bias.hex")]
    base = G.read_vectors(DATA / "tpu_vectors_mode1.txt")[:N_IMG]
    OUT.mkdir(parents=True, exist_ok=True)
    for mode in (0, 1, 2):
        lines = ["# SC-TPU sweep vectors (task RTL-TPU): pset 0, test positions 0..2, "
                 f"K = 4..10, s = 0/3/7, RNG_MODE={mode}",
                 "# generated by tests/tpu/gen_tpu_sweep_vectors.py with the golden model "
                 "code/python/sctpu/model.py (sc_inference_reference == sc_inference checked)",
                 "# one vector per line, 43 hex fields: pset K s mode idx label in[0..15] "
                 "hidden[0..3] score[0..15] result  (see sim/data/README.md)"]
        t0 = time.time()
        for K in K_LIST:
            for s in S_LIST:
                for v in base:
                    ref = M.sc_inference_reference(v["inputs"], ram, biases, K, s, mode)
                    fast = M.sc_inference(v["inputs"], ram, biases, K, s, mode)
                    if (ref.hidden != fast.hidden or ref.score != fast.score
                            or ref.result != fast.result):
                        print(f"MISMATCH reference vs fast: mode {mode} K {K} s {s} idx {v['idx']}")
                        return 1
                    lines.append(G.vector_line(0, K, s, mode, v["idx"], v["label"], v["inputs"],
                                               ref.hidden, ref.score, ref.result))
        path = OUT / f"tpu_vectors_sweep_mode{mode}.txt"
        G.write_lines(path, lines)
        print(f"wrote {path.relative_to(ROOT)}: {len(lines) - 3} vectors "
              f"(reference == fast for all), {time.time() - t0:.1f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
