"""Generator of the SoC demo program ``sim/data/soc_demo_prog.hex`` (task SW-01b).

The demo program is a TESTBENCH STIMULUS for the SoC-level simulation
(ARCHITECTURE.md section 8), not firmware.  It assumes that the SC-TPU weight
RAM, biases and input buffer are pre-initialised from their init files
(weights.hex / bias.hex / input.hex, ARCHITECTURE.md 5.6), so the CPU only:

1. writes CONFIG = LOG2_L | ACT_SHIFT << 4 with LOG2_L = 8 and ACT_SHIFT from
   the command line (default 0)            (TPU 0x2000_0008, bits [3:0], [6:4]);
2. writes CTRL = 1 (START)                 (TPU 0x2000_0000);
3. polls STATUS until DONE (bit 1) = 1     (TPU 0x2000_0004);
4. reads RESULT[3:0]                       (TPU 0x2000_000C);
5. writes RESULT to LED                    (0x1000_0000);
6. sends ASCII '0' + RESULT, then '\\n' on the UART, polling
   UART_STATUS.tx_busy (bit 0) = 0 before each byte (0x1000_0008 / 0x1000_0004);
7. reads the TPU CYCLES register (cycles of the last inference, 0x2000_0010)
   and stores it at RAM address 0x0E00;
8. writes TOHOST = 1 (0x1000_0010) and parks in ``j .``.

The program is checked on the ISS with the stub TPU (:class:`rv32.iss.TpuStub`)
for every RESULT 0..9, with BUSY polls so that the DONE loop iterates.

Usage (from the repository root)::

    .venv/bin/python code/python/rv32/gen_soc_demo.py [--act-shift S] [--out PATH]

Outputs: ``<out>.hex`` (1024 x 32-bit $readmemh image), ``<out>.lst``
(listing) and ``<out>.meta.json`` (expected behaviour as a function of RESULT).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

if __package__ in (None, ""):          # allow "python code/python/rv32/gen_soc_demo.py"
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    __package__ = "rv32"               # noqa: A001

from rv32.asm import Program, assemble  # noqa: E402
from rv32.disasm import roundtrip_mismatches  # noqa: E402
from rv32.iss import Iss, TpuStub  # noqa: E402

REPO = Path(__file__).resolve().parents[3]
DEFAULT_OUT = REPO / "sim" / "data" / "soc_demo_prog.hex"
LOG2_L = 8                 # SW-01b: stream length L = 2^8 = 256
CYCLES_ADDR = 0x0E00       # RAM word that receives the TPU CYCLES value


def demo_source(act_shift: int) -> str:
    """Assembly source of the demo program for a given ACT_SHIFT (0..7)."""
    if not 0 <= act_shift <= 7:
        raise ValueError("ACT_SHIFT is a 3-bit field (CONFIG[6:4]): 0..7")
    config = LOG2_L | (act_shift << 4)
    return f"""\
# SoC demo program (generated by code/python/rv32/gen_soc_demo.py) - testbench stimulus.
# CONFIG = LOG2_L {LOG2_L} | ACT_SHIFT {act_shift} << 4 = {config:#04x}
    .equ  CONFIG_VALUE, {config:#x}
    lui   x10, 0x20000           # x10 = 0x2000_0000 SC-TPU base
    lui   x11, 0x10000           # x11 = 0x1000_0000 peripheral base
    addi  x5, x0, CONFIG_VALUE
    sw    x5, 0x008(x10)         # TPU CONFIG <- LOG2_L | ACT_SHIFT << 4
    addi  x5, x0, 1
    sw    x5, 0x000(x10)         # TPU CTRL <- START
poll_done:
    lw    x6, 0x004(x10)         # TPU STATUS: [0] BUSY, [1] DONE
    andi  x6, x6, 2
    beq   x6, x0, poll_done      # wait for DONE = 1
    lw    x7, 0x00C(x10)         # TPU RESULT
    andi  x7, x7, 0xF            # [3:0] class
    sw    x7, 0x000(x11)         # LED <- RESULT
    addi  x8, x7, '0'            # ASCII digit
poll_tx1:
    lw    x9, 0x008(x11)         # UART_STATUS: [0] tx_busy
    andi  x9, x9, 1
    bne   x9, x0, poll_tx1
    sw    x8, 0x004(x11)         # UART_TX <- '0' + RESULT
    addi  x8, x0, '\\n'
poll_tx2:
    lw    x9, 0x008(x11)
    andi  x9, x9, 1
    bne   x9, x0, poll_tx2
    sw    x8, 0x004(x11)         # UART_TX <- '\\n'
    lw    x12, 0x010(x10)        # TPU CYCLES (cycles of the last inference)
    lui   x13, 0x1               # x13 = 0x1000
    sw    x12, {CYCLES_ADDR - 0x1000}(x13)        # [0x0E00] <- CYCLES
    addi  x5, x0, 1
tohost_store:
    sw    x5, 0x010(x11)         # TOHOST <- 1 (pass): testbench stops here
halt_loop:
    j     halt_loop
"""


def check_on_iss(prog: Program, act_shift: int) -> list[str]:
    """Run the demo on the ISS + TPU stub for RESULT 0..9; return error strings."""
    errors = []
    for result in range(10):
        for busy_polls in (0, 3):
            cycles = 0x1234_0000 + 17 * result + busy_polls      # arbitrary, distinct
            tpu = TpuStub(result=result, cycles=cycles, busy_polls=busy_polls)
            res = Iss(prog.image(), tpu=tpu).run(10_000)
            exp_uart = bytes([ord("0") + result, ord("\n")])
            checks = {
                "stop": (res.stop_reason, "tohost"),
                "tohost": (res.tohost, 1),
                "pc": (res.pc, prog.symbols["tohost_store"]),
                "config": (tpu.config_writes, [LOG2_L | act_shift << 4]),
                "starts": (tpu.starts, 1),
                "led": (res.led_writes, [result]),
                "uart": (res.uart, exp_uart),
                "cycles@0xE00": (res.word(CYCLES_ADDR), cycles),
                "bus_err": (res.bus_err, False),
            }
            for k, (got, exp) in checks.items():
                if got != exp:
                    errors.append(f"RESULT={result} busy_polls={busy_polls}: {k} = {got!r}, expected {exp!r}")
    return errors


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point.  Returns 0 if all ISS checks pass."""
    ap = argparse.ArgumentParser(description="Generate the SoC demo program (testbench stimulus).")
    ap.add_argument("--act-shift", type=int, default=0, help="CONFIG.ACT_SHIFT (0..7), default 0")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output .hex path")
    args = ap.parse_args(argv)

    prog = assemble(demo_source(args.act_shift))
    rt = roundtrip_mismatches(prog.words)
    errors = check_on_iss(prog, args.act_shift)
    if rt:
        errors.append(f"{len(rt)} disassembly round-trip mismatches: {rt[:3]}")
    out = args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    prog.write_hex(out)
    lst = out.with_suffix(".lst")
    lst.write_text(prog.listing_text(
        f"SoC demo program, ACT_SHIFT={args.act_shift}, LOG2_L={LOG2_L} "
        "(generated by code/python/rv32/gen_soc_demo.py)"))
    meta = {
        "name": out.stem,
        "generator": "code/python/rv32/gen_soc_demo.py",
        "act_shift": args.act_shift,
        "log2_l": LOG2_L,
        "config_value": f"0x{LOG2_L | args.act_shift << 4:02x}",
        "expected_led": "RESULT[3:0] (one LED write)",
        "expected_uart": "two bytes: 0x30 + RESULT, 0x0a",
        "cycles_store_addr": f"0x{CYCLES_ADDR:08x}",
        "cycles_store_value": "TPU CYCLES register read after DONE",
        "expected_tohost": 1,
        "tohost_pc": f"0x{prog.symbols['tohost_store']:08x}",
        "requires": ["ram", "tohost", "led", "uart", "tpu (pre-initialised weights/bias/input)"],
        "iss_check": "RESULT 0..9 x busy_polls {0,3} on the TPU stub",
        "iss_check_errors": errors,
        "roundtrip_mismatches": len(rt),
        "code_bytes": prog.end,
        "hex_sha256": hashlib.sha256(out.read_bytes()).hexdigest(),
    }
    out.with_suffix(".meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"gen_soc_demo: ACT_SHIFT={args.act_shift} CONFIG={meta['config_value']} "
          f"code={prog.end} bytes -> {out}")
    print(f"round-trip mismatches: {len(rt)}")
    print(f"ISS checks (RESULT 0..9 x busy_polls 0/3 = 20 runs): {len(errors)} errors")
    for e in errors:
        print("  ERROR", e)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
