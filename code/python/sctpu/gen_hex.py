"""Generate SC-TPU init files and RTL test vectors (task SW-01a, deliverable 4).

Outputs in ``sim/data/`` (formats documented in ``sim/data/README.md``):

* ``weights.hex`` — 512 x 32-bit words of the weight RAM (ARCHITECTURE.md 5.5, 5.6);
* ``bias.hex``    — 32 x 16-bit two's-complement biases, 4 hex digits (5.4, 5.6);
* ``input.hex``   — 16 x 32-bit INPUT words of test image 0 (5.4, 5.6);
* ``tpu_vectors_mode{0,1,2}.txt`` — K=8, the trained s, all 360 test images;
* ``tpu_vectors_K4_mode1.txt``, ``tpu_vectors_K10_mode1.txt`` — short sets (16 images);
* ``tpu_vectors_corner_mode{0,1,2}.txt`` + ``corner/pset<n>_{weights,bias}.hex`` —
  hand-crafted corner cases at K=4;
* ``tpu_rng_trace_mode{0,1,2}.txt`` — LFSR states and lane r values of the first
  64 stream cycles after START (debug aid for bit-exactness, 5.3).

Expected values come from the fast exact model ``model.sc_inference_batch``;
a subset of every file is recomputed with the slow literal reference
``model.sc_inference_reference`` and the number of mismatching fields is
printed (bit-exactness evidence, logged to logs/sw/gen_hex.log).

Hex conventions (python-model-flow skill): lowercase, no ``0x``, fixed width,
one word per line. The three init files have NO header line so that they have
exactly the line counts given in 5.6.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

from . import lfsr
from . import model as M
from . import train as T

DATA_DIR = T.DATA_DIR
CORNER_DIR = DATA_DIR / "corner"
K_MAIN = 8
N_SHORT = 16
K_CORNER = 4
CORNER_SEED = 2026  #: numpy seed of the random corner-case contents
N_REF_CHECK = 24  #: vectors per file re-checked with the slow reference
N_FIELDS = 43
NA_LABEL = 0xF  #: label field value for vectors without a dataset label


# ---------------------------------------------------------------------------
# Writers
# ---------------------------------------------------------------------------

def write_lines(path: Path, lines: list[str]) -> None:
    """Write text lines with a trailing newline (LF)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def write_weights_hex(path: Path, ram: np.ndarray) -> None:
    """512 lines of 8 hex digits: word w = RAM bytes 4w..4w+3 little-endian (5.5)."""
    words = M.bytes_to_words(ram)
    assert len(words) == 512
    write_lines(path, [f"{w:08x}" for w in words])


def write_bias_hex(path: Path, biases: np.ndarray) -> None:
    """32 lines of 4 hex digits, 16-bit two's complement, index b = 16(l-1)+j (5.4)."""
    assert len(biases) == M.N_BIAS
    write_lines(path, [f"{M.to_u16(int(b)):04x}" for b in biases])


def write_input_hex(path: Path, codes: np.ndarray) -> None:
    """16 lines of 8 hex digits: INPUT codes packed 4 per word little-endian (5.4)."""
    words = M.input_words(codes)
    assert len(words) == 16
    write_lines(path, [f"{w:08x}" for w in words])


def vector_line(pset: int, K: int, s: int, mode: int, idx: int, label: int,
                inputs, hidden, score, result: int) -> str:
    """One test vector = one line of 43 space-separated hex fields (README.md)."""
    f = [f"{pset:x}", f"{K:x}", f"{s:x}", f"{mode:x}", f"{idx:x}", f"{label:x}"]
    f += [f"{w:08x}" for w in M.input_words(inputs)]
    f += [f"{w:08x}" for w in M.hidden_words(hidden)]
    f += [f"{w:08x}" for w in M.score_words(score)]
    f += [f"{result:x}"]
    assert len(f) == N_FIELDS
    return " ".join(f)


def header(title: str, extra: list[str]) -> list[str]:
    """Common '#' header of the vector files (format reminder + provenance)."""
    return ["# " + title,
            "# generated by code/python/sctpu/gen_hex.py (task SW-01a), rev " + T.git_rev(),
            "# spec: design/architecture/ARCHITECTURE.md rev A section 5 (bit-exact)",
            "# one vector per line, 43 hex fields: pset K s mode idx label "
            "in[0..15] hidden[0..3] score[0..15] result  (see sim/data/README.md)"] + \
           ["# " + e for e in extra]


def make_vectors(codes: np.ndarray, ram, biases, K, s, mode, pset, labels, idxs) -> list[str]:
    """Run the fast exact model on a batch and format the vector lines."""
    r = M.sc_inference_batch(codes, ram, biases, K, s, mode)
    return [vector_line(pset, K, s, mode, int(idxs[n]), int(labels[n]), codes[n],
                        r["hidden"][n], r["score"][n], int(r["result"][n]))
            for n in range(len(codes))]


# ---------------------------------------------------------------------------
# Parsing (used for the reference cross-check and by the unit tests)
# ---------------------------------------------------------------------------

def parse_vector_line(line: str) -> dict:
    """Parse one vector line back into integers (inverse of :func:`vector_line`)."""
    f = [int(t, 16) for t in line.split()]
    if len(f) != N_FIELDS:
        raise ValueError(f"expected {N_FIELDS} fields, got {len(f)}")
    score = [v - (1 << 32) if v & 0x80000000 else v for v in f[26:42]]
    return {"pset": f[0], "K": f[1], "s": f[2], "mode": f[3], "idx": f[4], "label": f[5],
            "inputs": M.words_to_bytes(f[6:22]), "hidden": M.words_to_bytes(f[22:26]),
            "score": score, "result": f[42]}


def read_vectors(path: Path) -> list[dict]:
    """Read all non-comment lines of a vector file."""
    return [parse_vector_line(ln) for ln in path.read_text().splitlines()
            if ln.strip() and not ln.startswith("#")]


def read_hex(path: Path) -> list[int]:
    """Read a $readmemh-style file (no comments expected) into ints."""
    return [int(ln, 16) for ln in path.read_text().split()]


# ---------------------------------------------------------------------------
# Corner cases
# ---------------------------------------------------------------------------

def corner_psets(trained_ram: np.ndarray, trained_b: np.ndarray) -> list[dict]:
    """Hand-crafted parameter sets (pset 1..8) with their special input patterns.

    Each entry: name, weight RAM, biases, purpose, list of input patterns.
    Random contents use ``default_rng(CORNER_SEED)``.
    """
    rng = np.random.default_rng(CORNER_SEED)
    rnd_w1 = rng.integers(0, 256, (16, 64))
    rnd_w2 = rng.integers(0, 256, (16, 16))
    rnd_in = rng.integers(0, 256, 64)
    ps = []
    # 1: everything zero -> all SNG bits 0, XNOR always 1 (deterministic acc).
    ps.append({"name": "all_zero_codes", "ram": np.zeros(2048, np.uint8),
               "b": np.zeros(32, np.int64), "inputs": [np.zeros(64, np.int64)],
               "purpose": "codes 0: SNG bit (r<0) never 1; acc1 = 64L, hidden saturates at 255"})
    # 2: everything 255 -> bits 1 except when r = 255.
    ps.append({"name": "all_255_codes", "ram": np.full(2048, 255, np.uint8),
               "b": np.zeros(32, np.int64), "inputs": [np.full(64, 255, np.int64)],
               "purpose": "codes 255: bit 0 only when r=255"})
    # 3/4: saturating biases.
    ram_r = M.pack_weight_ram(rnd_w1, rnd_w2, fill_code=0)
    ps.append({"name": "bias_sat_pos", "ram": ram_r, "b": np.full(32, 32767, np.int64),
               "inputs": [rnd_in], "purpose": "bias +32767: B max, hidden clipped at 127"})
    ps.append({"name": "bias_sat_neg", "ram": ram_r, "b": np.full(32, -32768, np.int64),
               "inputs": [rnd_in], "purpose": "bias -32768: B min, hidden clipped at 0, negative scores"})
    # 5: full tie in layer 2: all layer-2 weights 0 and equal biases -> RESULT 0.
    w2 = np.zeros((16, 16), np.int64)
    b5 = np.concatenate([rng.integers(-3000, 3000, 16), np.full(16, 100)])
    ps.append({"name": "argmax_tie_all", "ram": M.pack_weight_ram(rnd_w1, w2), "b": b5,
               "inputs": [rnd_in], "purpose": "identical layer-2 rows+biases: all 16 scores equal -> RESULT 0"})
    # 6: tie between lanes 3 and 7, padding lanes larger (must be ignored) -> RESULT 3.
    w2 = rng.integers(0, 256, (16, 16))
    w2[7] = w2[3]
    b6 = np.concatenate([rng.integers(-3000, 3000, 16),
                         np.array([-20000] * 3 + [20000] + [-20000] * 3 + [20000] + [-20000] * 2
                                  + [32767] * 6)])
    ps.append({"name": "argmax_tie_3_7_padding_max", "ram": M.pack_weight_ram(rnd_w1, w2), "b": b6,
               "inputs": [rnd_in],
               "purpose": "lanes 3 and 7 identical (tie -> 3); padding lanes 10..15 larger but ignored"})
    # 7: random everything, full int16 bias range.
    b7 = rng.integers(-32768, 32768, 32)
    ps.append({"name": "random_full_range", "ram": M.pack_weight_ram(rng.integers(0, 256, (16, 64)),
                                                                       rng.integers(0, 256, (16, 16))),
               "b": b7, "inputs": [rng.integers(0, 256, 64), rnd_in],
               "purpose": "random codes and biases over the full ranges"})
    # 8: small negative biases -> floor(bias*2^K/128) at K=4 differs from truncation.
    b8 = np.concatenate([-np.arange(1, 17), -np.arange(1, 17) * 7])
    ps.append({"name": "small_negative_bias_floor", "ram": trained_ram, "b": b8,
               "inputs": [rnd_in],
               "purpose": "bias -1..-16 / -7..-112: B = floor(bias*2^K/128) (floor, not truncation)"})
    return ps


# ---------------------------------------------------------------------------
# RNG trace
# ---------------------------------------------------------------------------

def rng_trace_lines(mode: int, n_cycles: int = 64) -> list[str]:
    """LFSR states and lane r values of the first stream cycles (5.3)."""
    sx, sw = M.lane_seeds(mode)
    sx, sw = list(sx), list(sw)
    lines = header(f"SC-TPU RNG trace, RNG_MODE={mode}, first {n_cycles} stream cycles after START", [
        "fields (hex): cycle, LFSR_X state(s) [" + str(len(sx)) + "], LFSR_W state(s) [" + str(len(sw))
        + "], r_x lane 0..7, r_w lane 0..7",
        "seeds (loaded on START, never used as r): X " + " ".join(f"{v:04x}" for v in sx)
        + " / W " + " ".join(f"{v:04x}" for v in sw)])
    lines = [ln for ln in lines if "43 hex fields" not in ln]
    rx, rw = M.rng_streams(mode, n_cycles)
    for k in range(n_cycles):
        sx = [lfsr.leap8(v) for v in sx]
        sw = [lfsr.leap8(v) for v in sw]
        f = [f"{k:x}"] + [f"{v:04x}" for v in sx] + [f"{v:04x}" for v in sw]
        f += [f"{int(v):02x}" for v in rx[:, k]] + [f"{int(v):02x}" for v in rw[:, k]]
        lines.append(" ".join(f))
    return lines


# ---------------------------------------------------------------------------
# Reference cross-check
# ---------------------------------------------------------------------------

def crosscheck(path: Path, psets: dict, n_max: int) -> tuple[int, int]:
    """Recompute up to ``n_max`` vectors of ``path`` with the slow reference.

    Returns (vectors checked, mismatching fields). Fields compared: 16 HIDDEN
    codes, 16 SCORE values, RESULT (33 per vector).
    """
    vecs = read_vectors(path)
    step = max(1, len(vecs) // n_max)
    chosen = vecs[::step][:n_max]
    bad = 0
    for v in chosen:
        ram, b = psets[v["pset"]]
        r = M.sc_inference_reference(v["inputs"], ram, b, v["K"], v["s"], v["mode"])
        bad += sum(int(a != c) for a, c in zip(r.hidden, v["hidden"]))
        bad += sum(int(a != c) for a, c in zip(r.score, v["score"]))
        bad += int(r.result != v["result"])
    return len(chosen), bad


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> int:
    """Generate every file and print the cross-check summary."""
    mp = json.loads((DATA_DIR / "model_params.json").read_text())
    s = int(mp["act_shift_s"])
    ram = M.pack_weight_ram(np.array(mp["w1_codes"]), np.array(mp["w2_codes"]))
    biases = M.pack_biases(mp["b1_int16"], mp["b2_int16"])
    d = T.load_split()
    te = np.array(mp["test_indices"])
    assert np.array_equal(te, d["test_idx"])
    codes, labels = d["codes"][te], d["y"][te]
    print(f"# gen_hex.py rev={T.git_rev()} variant={mp['variant']} s={s} test images={len(te)}")

    write_weights_hex(DATA_DIR / "weights.hex", ram)
    write_bias_hex(DATA_DIR / "bias.hex", biases)
    write_input_hex(DATA_DIR / "input.hex", codes[0])
    print(f"input.hex = test position 0 = load_digits row {te[0]}, label {labels[0]}")

    files = []
    idx_all = np.arange(len(te))
    for mode in M.RNG_MODES:
        p = DATA_DIR / f"tpu_vectors_mode{mode}.txt"
        lines = header(f"SC-TPU test vectors: trained model (pset 0), K={K_MAIN}, s={s}, RNG_MODE={mode}, "
                       f"all {len(te)} test images", [
                           "pset 0 = weights.hex + bias.hex; idx = position in test_indices of model_params.json"])
        lines += make_vectors(codes, ram, biases, K_MAIN, s, mode, 0, labels, idx_all)
        write_lines(p, lines)
        files.append(p)
    for K in (4, 10):
        p = DATA_DIR / f"tpu_vectors_K{K}_mode1.txt"
        lines = header(f"SC-TPU test vectors: trained model (pset 0), K={K}, s={s}, RNG_MODE=1, "
                       f"first {N_SHORT} test images", ["pset 0 = weights.hex + bias.hex"])
        lines += make_vectors(codes[:N_SHORT], ram, biases, K, s, 1, 0, labels[:N_SHORT], idx_all[:N_SHORT])
        write_lines(p, lines)
        files.append(p)

    # corner cases
    psets = {0: (ram, biases)}
    cps = corner_psets(ram, biases)
    corner_desc = []
    for n, c in enumerate(cps, start=1):
        write_weights_hex(CORNER_DIR / f"pset{n}_weights.hex", c["ram"])
        write_bias_hex(CORNER_DIR / f"pset{n}_bias.hex", c["b"])
        psets[n] = (c["ram"], c["b"])
        corner_desc.append(f"pset {n}: {c['name']} — {c['purpose']}")
    for mode in M.RNG_MODES:
        p = DATA_DIR / f"tpu_vectors_corner_mode{mode}.txt"
        lines = header(f"SC-TPU corner-case vectors, K={K_CORNER}, RNG_MODE={mode}",
                       ["pset n>0 = corner/pset<n>_weights.hex + corner/pset<n>_bias.hex; "
                        "idx = input pattern number (0 = pset pattern(s), last = test image 0); label f = n/a"]
                       + corner_desc)
        for n, c in enumerate(cps, start=1):
            pats = list(c["inputs"]) + [codes[0]]
            for s_c in (0, 3, 7):
                X = np.array(pats, dtype=np.int64)
                lines += make_vectors(X, c["ram"], c["b"], K_CORNER, s_c, mode, n,
                                      [NA_LABEL] * len(X), range(len(X)))
        write_lines(p, lines)
        files.append(p)
    for mode in M.RNG_MODES:
        write_lines(DATA_DIR / f"tpu_rng_trace_mode{mode}.txt", rng_trace_lines(mode))

    # self-checks: round trip of the init files, reference cross-check
    assert M.words_to_bytes(read_hex(DATA_DIR / "weights.hex")) == [int(v) for v in ram]
    assert [v - 65536 if v & 0x8000 else v for v in read_hex(DATA_DIR / "bias.hex")] == [int(v) for v in biases]
    assert M.words_to_bytes(read_hex(DATA_DIR / "input.hex")) == [int(v) for v in codes[0]]
    total_v, total_bad = 0, 0
    for p in files:
        n_lines = len(read_vectors(p))
        nv, bad = crosscheck(p, psets, N_REF_CHECK if "corner" not in p.name else 10 ** 6)
        total_v += nv
        total_bad += bad
        print(f"{p.name}: {n_lines} vectors; reference cross-check {nv} vectors, {bad} mismatching fields")
    print(f"CROSSCHECK TOTAL: {total_v} vectors x 33 fields, mismatches = {total_bad}")
    # Corner-case expectations that hold by construction (sanity):
    for mode in M.RNG_MODES:
        for v in read_vectors(DATA_DIR / f"tpu_vectors_corner_mode{mode}.txt"):
            if v["pset"] == 5:
                assert v["result"] == 0 and len(set(v["score"])) == 1
            if v["pset"] == 6:
                assert v["score"][3] == v["score"][7] and v["result"] == 3, v
            if v["pset"] == 1 and v["idx"] == 0:
                assert v["hidden"] == [255] * 16
    print("corner-case sanity assertions: PASS (pset1 hidden=255, pset5 full tie->0, pset6 tie 3/7->3)")
    return 1 if total_bad else 0


if __name__ == "__main__":
    sys.exit(main())
