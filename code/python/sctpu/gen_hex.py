def soc_expected(codes0: np.ndarray, ram, biases, label0: int, row0: int, spec_rev: str) -> dict:
    """Golden SoC-level expectation for ``input.hex`` (test image 0) at K=8, s=0, mode 2.

    Computed with the fast model and re-computed with the slow literal
    reference (field-by-field mismatch count stored in the file). The SoC demo
    program (sim/data/soc_demo_prog.hex) writes CONFIG = 0x08 and START, polls
    DONE, reads RESULT, writes LED = RESULT and sends '0'+RESULT, '\n' on the UART.
    """
    fast = M.sc_inference(codes0, ram, biases, SOC_K, SOC_S, SOC_MODE, spec_rev)
    ref = M.sc_inference_reference(codes0, ram, biases, SOC_K, SOC_S, SOC_MODE, spec_rev)
    mism = (sum(int(a != b) for a, b in zip(fast.hidden, ref.hidden))
            + sum(int(a != b) for a, b in zip(fast.score, ref.score)) + int(fast.result != ref.result))
    ev = M.ev_inference(codes0, ram, biases, SOC_S)
    sx, sw = M.lane_seeds(SOC_MODE, spec_rev)
    return {
        "label": "SIMULATION (Python golden model code/python/sctpu/model.py; not a hardware measurement)",
        "generator": "code/python/sctpu/gen_hex.py (task SW-02)",
        "git_rev": T.git_rev(),
        "spec_rev": spec_rev,
        "spec": "design/architecture/ARCHITECTURE.md section 5 + section 11 (ADR-008); INTERFACES.json revision B",
        "input_file": "sim/data/input.hex",
        "input_sha256": hashlib.sha256((DATA_DIR / "input.hex").read_bytes()).hexdigest(),
        "weights_sha256": hashlib.sha256((DATA_DIR / "weights.hex").read_bytes()).hexdigest(),
        "bias_sha256": hashlib.sha256((DATA_DIR / "bias.hex").read_bytes()).hexdigest(),
        "image": {"test_position": 0, "load_digits_row": int(row0), "dataset_label": int(label0)},
        "K": SOC_K, "act_shift_s": SOC_S, "rng_mode": SOC_MODE,
        "config_write": f"0x{SOC_K | (SOC_S << 4):02x}",
        "params_expected": f"0x{M.params_word(SOC_MODE, spec_rev):08x}",
        "seeds_x": [f"0x{v:04x}" for v in sx], "seeds_w": [f"0x{v:04x}" for v in sw],
        "hidden_codes": [int(v) for v in fast.hidden],
        "hidden_words": [f"0x{w:08x}" for w in M.hidden_words(fast.hidden)],
        "score": [int(v) for v in fast.score],
        "score_words": [f"0x{w:08x}" for w in M.score_words(fast.score)],
        "score_note": "SCORE[j] at TPU 0x2000_0080 + 4j; all 16 lanes (10..15 = padding, ignored by argmax)",
        "result": int(fast.result),
        "expected_led": int(fast.result),
        "expected_uart_bytes": [f"0x{0x30 + int(fast.result):02x}", "0x0a"],
        "expected_tohost": 1,
        "cycles": "not part of the bit-exact spec (RTL-defined, ARCHITECTURE.md 10); not checked here",
        "reference_crosscheck_mismatching_fields": mism,
        "expected_value_Kinf_result": int(ev["result"][0]),
        "result_equals_dataset_label": int(fast.result) == int(label0),
    }


def main(argv=None) -> int:
    """Generate every file and print the cross-check summary."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--spec-rev", choices=M.SPEC_REVS, default=M.DEFAULT_SPEC_REV,
                    help="seed rule (default %(default)s = ARCHITECTURE.md 11)")
    ap.add_argument("--out", type=Path, default=DATA_DIR, help="output directory (default sim/data)")
    ap.add_argument("--full-check-mode", type=int, default=M.DEFAULT_RNG_MODE,
                    help="RNG_MODE whose 360-vector file is re-checked completely with the slow reference")
    args = ap.parse_args(argv)
    spec_rev, out = args.spec_rev, args.out
    corner_dir = out / "corner"
    mp = json.loads((DATA_DIR / "model_params.json").read_text())
    s = int(mp["act_shift_s"])
    ram = M.pack_weight_ram(np.array(mp["w1_codes"]), np.array(mp["w2_codes"]))
    biases = M.pack_biases(mp["b1_int16"], mp["b2_int16"])
    d = T.load_split()
    te = np.array(mp["test_indices"])
    assert np.array_equal(te, d["test_idx"])
    codes, labels = d["codes"][te], d["y"][te]
    print(f"# gen_hex.py rev={T.git_rev()} spec_rev={spec_rev} out={out} variant={mp['variant']} "
          f"s={s} test images={len(te)}")
    sx, sw = M.lane_seeds(2, spec_rev)
    print(f"# seeds modes 0/1: X {M.lane_seeds(0, spec_rev)[0][0]:04x} W {M.lane_seeds(0, spec_rev)[1][0]:04x}; "
          f"mode 2: X " + " ".join(f"{v:04x}" for v in sx) + " / W " + " ".join(f"{v:04x}" for v in sw))

    write_weights_hex(out / "weights.hex", ram)
    write_bias_hex(out / "bias.hex", biases)
    write_input_hex(out / "input.hex", codes[0])
    print(f"input.hex = test position 0 = load_digits row {te[0]}, label {labels[0]}")

    files = []
    idx_all = np.arange(len(te))
    for mode in M.RNG_MODES:
        p = out / f"tpu_vectors_mode{mode}.txt"
        lines = header(f"SC-TPU test vectors: trained model (pset 0), K={K_MAIN}, s={s}, RNG_MODE={mode}, "
                       f"all {len(te)} test images", [
                           "pset 0 = weights.hex + bias.hex; idx = position in test_indices of model_params.json"],
                       spec_rev)
        lines += make_vectors(codes, ram, biases, K_MAIN, s, mode, 0, labels, idx_all, spec_rev)
        write_lines(p, lines)
        files.append(p)
    for K in (4, 10):
        p = out / f"tpu_vectors_K{K}_mode1.txt"
        lines = header(f"SC-TPU test vectors: trained model (pset 0), K={K}, s={s}, RNG_MODE=1, "
                       f"first {N_SHORT} test images", ["pset 0 = weights.hex + bias.hex"], spec_rev)
        lines += make_vectors(codes[:N_SHORT], ram, biases, K, s, 1, 0, labels[:N_SHORT], idx_all[:N_SHORT],
                              spec_rev)
        write_lines(p, lines)
        files.append(p)

    # corner cases
    psets = {0: (ram, biases)}
    cps = corner_psets(ram, biases)
    corner_desc = []
    for n, c in enumerate(cps, start=1):
        write_weights_hex(corner_dir / f"pset{n}_weights.hex", c["ram"])
        write_bias_hex(corner_dir / f"pset{n}_bias.hex", c["b"])
        psets[n] = (c["ram"], c["b"])
        corner_desc.append(f"pset {n}: {c['name']} — {c['purpose']}")
    for mode in M.RNG_MODES:
        p = out / f"tpu_vectors_corner_mode{mode}.txt"
        lines = header(f"SC-TPU corner-case vectors, K={K_CORNER}, RNG_MODE={mode}",
                       ["pset n>0 = corner/pset<n>_weights.hex + corner/pset<n>_bias.hex; "
                        "idx = input pattern number (0 = pset pattern(s), last = test image 0); label f = n/a"]
                       + corner_desc, spec_rev)
        for n, c in enumerate(cps, start=1):
            pats = list(c["inputs"]) + [codes[0]]
            for s_c in (0, 3, 7):
                X = np.array(pats, dtype=np.int64)
                lines += make_vectors(X, c["ram"], c["b"], K_CORNER, s_c, mode, n,
                                      [NA_LABEL] * len(X), range(len(X)), spec_rev)
        write_lines(p, lines)
        files.append(p)
    for mode in M.RNG_MODES:
        write_lines(out / f"tpu_rng_trace_mode{mode}.txt", rng_trace_lines(mode, spec_rev))

    # self-checks: round trip of the init files, reference cross-check
    assert M.words_to_bytes(read_hex(out / "weights.hex")) == [int(v) for v in ram]
    assert [v - 65536 if v & 0x8000 else v for v in read_hex(out / "bias.hex")] == [int(v) for v in biases]
    assert M.words_to_bytes(read_hex(out / "input.hex")) == [int(v) for v in codes[0]]
    total_v, total_bad = 0, 0
    for p in files:
        assert read_spec_rev(p) == spec_rev
        n_lines = len(read_vectors(p))
        full = "corner" in p.name or p.name == f"tpu_vectors_mode{args.full_check_mode}.txt"
        nv, bad = crosscheck(p, psets, 10 ** 6 if full else N_REF_CHECK)
        total_v += nv
        total_bad += bad
        print(f"{p.name}: {n_lines} vectors; reference cross-check {nv} vectors, {bad} mismatching fields")
    print(f"CROSSCHECK TOTAL: {total_v} vectors x 33 fields, mismatches = {total_bad}")
    # Corner-case expectations that hold by construction (sanity):
    for mode in M.RNG_MODES:
        for v in read_vectors(out / f"tpu_vectors_corner_mode{mode}.txt"):
            if v["pset"] == 5:
                assert v["result"] == 0 and len(set(v["score"])) == 1
            if v["pset"] == 6:
                assert v["score"][3] == v["score"][7] and v["result"] == 3, v
            if v["pset"] == 1 and v["idx"] == 0:
                assert v["hidden"] == [255] * 16
    print("corner-case sanity assertions: PASS (pset1 hidden=255, pset5 full tie->0, pset6 tie 3/7->3)")

    # SoC-level golden expectation (rev B default configuration only)
    if spec_rev == M.DEFAULT_SPEC_REV and out.resolve() == DATA_DIR.resolve():
        se = soc_expected(codes[0], ram, biases, int(labels[0]), int(te[0]), spec_rev)
        (out / "soc_expected.json").write_text(json.dumps(se, indent=1) + "\n")
        total_bad += se["reference_crosscheck_mismatching_fields"]
        print(f"soc_expected.json: K={SOC_K} s={SOC_S} mode={SOC_MODE} rev {spec_rev}: RESULT={se['result']} "
              f"(label {se['image']['dataset_label']}, EV {se['expected_value_Kinf_result']}), "
              f"SCORE[0..9]={se['score'][:10]}, reference mismatches = "
              f"{se['reference_crosscheck_mismatching_fields']}")
    print(f"FINAL MISMATCH COUNT (vectors + soc_expected): {total_bad}")
    return 1 if total_bad else 0


