#!/usr/bin/env python3
"""Convert CPU-test metadata (JSON) into a $readmemh companion file for the RTL TB.

Task RTL-CPU (fpga-engineer).  Parsing JSON in Verilog-2005 is impractical, so
for every test listed in ``<test_dir>/index.txt`` this script reads
``<test_dir>/<name>.meta.json`` (written by code/python/rv32/gen_cpu_tests.py,
task SW-01b - used READ-ONLY here, never modified) and writes
``<out_dir>/<name>.tbmeta.hex``: a plain list of 32-bit hex words that
tests/cpu/tb_rv32i_core.v loads with ``$readmemh`` (``+meta=<file>``).

Companion file layout (one 32-bit hex word per line, ``//`` comments allowed
by $readmemh; the TB indexes the words by position):

    word 0  stop kind            0 = TOHOST write, 1 = trap (halted)
    word 1  trap cause           INTERFACES.json cpu.traps (0 for TOHOST stop)
    word 2  stop PC              halt PC (trap) or PC of the TOHOST store
    word 3  instret              retired instructions at the stop point
                                 (trapping instruction NOT counted, TOHOST store counted)
    word 4  TOHOST written       1 if a TOHOST write is expected, else 0
    word 5  TOHOST value         expected value (0 if not written)
    word 6  bus_err              expected sticky unmapped-access flag (0/1)
    word 7  LED                  expected LED register value [5:0]
    word 8  UART length N        number of bytes expected on UART_TX
    word 9 .. 9+N-1              the UART bytes, one per word
    (N is limited to 256 by the TB array size; the script refuses more.)
    The file is padded with zero words to exactly META_WORDS = 9 + 256 lines
    so that $readmemh fills the whole TB array (no "not enough words" warning).

Integrity: the sha256 of ``<name>.hex`` and ``<name>.sig`` recorded in the
meta file is re-computed and must match, so the TB never runs a stimulus that
differs from the one the ISS produced the expectations for.

Usage::

    python scripts/cpu_meta_to_tb.py <test_dir> <out_dir>

Exit status 0 if every test converted, 1 otherwise.  Prints one line per test.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

UART_MAX = 256           # must match UART_MAX in tests/cpu/tb_rv32i_core.v
META_WORDS = 9 + UART_MAX  # must match META_WORDS in tests/cpu/tb_rv32i_core.v


def sha256(path: Path) -> str:
    """Hex sha256 of a file."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def convert(test_dir: Path, out_dir: Path, name: str) -> str:
    """Write <out_dir>/<name>.tbmeta.hex; return a one-line description."""
    meta = json.loads((test_dir / f"{name}.meta.json").read_text())
    for kind in ("hex", "sig"):
        want = meta.get(f"{kind}_sha256")
        got = sha256(test_dir / f"{name}.{kind}")
        if want is not None and want != got:
            raise ValueError(f"{name}.{kind}: sha256 {got} != meta {want}")

    stop = meta["expected_stop"]
    if stop not in ("tohost", "trap"):
        raise ValueError(f"{name}: unknown expected_stop {stop!r}")
    trap = stop == "trap"
    pc_txt = meta["expected_halt_pc"] if trap else meta["tohost_pc"]
    tohost = meta.get("expected_tohost")
    uart = meta.get("expected_uart", "") or ""
    uart_bytes = uart.encode("latin-1")
    if len(uart_bytes) > UART_MAX:
        raise ValueError(f"{name}: {len(uart_bytes)} UART bytes > TB limit {UART_MAX}")

    words = [
        (1 if trap else 0, "stop kind (0 tohost, 1 trap)"),
        (int(meta["expected_trap_cause"]), f"trap cause ({meta.get('expected_trap_name')})"),
        (int(pc_txt, 16), "stop pc (halt pc or TOHOST store pc)"),
        (int(meta["instret"]), "instret"),
        (0 if tohost is None else 1, "TOHOST written"),
        (0 if tohost is None else int(tohost), "TOHOST value"),
        (1 if meta.get("expected_bus_err") else 0, "bus_err"),
        (int(meta.get("expected_led", 0)), "LED"),
        (len(uart_bytes), "UART length"),
    ] + [(b, f"uart[{i}]") for i, b in enumerate(uart_bytes)]
    words += [(0, "pad")] * (META_WORDS - len(words))

    lines = [f"// generated by scripts/cpu_meta_to_tb.py from {test_dir / (name + '.meta.json')}"]
    lines += [f"{v & 0xFFFFFFFF:08x}  // {i}: {c}" for i, (v, c) in enumerate(words)]
    (out_dir / f"{name}.tbmeta.hex").write_text("\n".join(lines) + "\n")
    return (f"{name}: stop={stop} cause={meta['expected_trap_cause']} pc={pc_txt} "
            f"instret={meta['instret']} tohost={tohost} bus_err={meta.get('expected_bus_err')} "
            f"led={meta.get('expected_led')} uart_len={len(uart_bytes)}")


def main(argv: list[str]) -> int:
    """Entry point."""
    if len(argv) != 3:
        print(__doc__)
        return 1
    test_dir, out_dir = Path(argv[1]), Path(argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)
    names = [n.strip() for n in (test_dir / "index.txt").read_text().splitlines() if n.strip()]
    errors = 0
    for name in names:
        try:
            print("META " + convert(test_dir, out_dir, name))
        except (OSError, ValueError, KeyError) as exc:
            print(f"META-ERROR {name}: {exc}")
            errors += 1
    print(f"converted {len(names) - errors}/{len(names)} meta files into {out_dir}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
