#!/usr/bin/env bash
# =============================================================================
# scripts/synth_tpu_variants.sh  -  RTL-TPU synthesis + P&R and variant study
#                                   (fpga-engineer, task RTL-TPU)
#
# Flow (identical for every variant; only the two parameters change):
#   yowasp-yosys     read design/rtl/tpu/*.v + sc_tpu_synth_top.v,
#                    chparam IL / RNG_MODE / init files, synth_gowin, stat
#   nextpnr-himbaechel-gowin  GW1NR-LV9QN88PC6/I5, family GW1N-9C,
#                    design/constraints/tangnano9k.cst, --freq 27, single
#                    thread, seeds $SEEDS, WITHOUT --timing-allow-fail
# Variants: IL=8 RNG_MODE=0/1/2, and IL=4/16 at RNG_MODE=1 (IL is a
#           synthesis-only study, ADR-002; rev A freezes IL=8).
# Init files: sim/data/weights.hex, bias.hex, input.hex (SW-01a) for all
#           variants (they only set BSRAM/LUTRAM INIT values, not the area).
#
# Usage   : bash scripts/synth_tpu_variants.sh          (all variants)
#           VARIANTS="il8_m1" SEEDS="1 2 3" bash scripts/synth_tpu_variants.sh
# Outputs : logs/tpu/synth_<v>.log, logs/tpu/pnr_<v>_s<seed>.log,
#           reports/fpga/tpu/variants.md (table), reports/fpga/tpu/<v>_*.txt
#           (utilisation, critical path), build products in sim/tpu/build/
# NOTE    : YoWASP tools only see the working-directory tree: all paths are
#           relative to the project root. One P&R at a time (shared cores).
# =============================================================================
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
# shellcheck disable=SC1091
source "$ROOT/.venv/bin/activate"

LOG=logs/tpu
REP=reports/fpga/tpu
B=sim/tpu/build
mkdir -p "$LOG" "$REP" "$B"
D=design/rtl/tpu
RTL="$D/sc_lfsr8.v $D/sc_rng.v $D/sc_lane_array.v $D/sc_postproc.v $D/sc_tpu_ctrl.v $D/sc_tpu.v $D/sc_tpu_synth_top.v"
TOP=sc_tpu_synth_top
CST=design/constraints/tangnano9k.cst
DEVICE=GW1NR-LV9QN88PC6/I5
FAMILY=GW1N-9C
VARIANTS=${VARIANTS:-"il8_m1 il8_m0 il8_m2 il4_m1 il16_m1"}
SEEDS=${SEEDS:-"1 2 3"}

REV="$(git rev-parse --short HEAD 2>/dev/null || echo no-commit)"
if [ -n "$(git status --porcelain -- design/rtl/tpu 2>/dev/null)" ]; then REV="${REV}-dirty"; fi
YOSYS_V="$(yowasp-yosys -V 2>&1 | sed -n 1p)"
PNR_V="$(yowasp-nextpnr-himbaechel-gowin --version 2>&1 | sed -n 1p)"

fail() { echo "SYNTH_TPU FAIL: $*" >&2; exit 1; }

# Inference latency formula (sc_tpu_ctrl.v, CALCULATION):
#   CYCLES = (64/IL + 16/IL) * (NL*IL/4 + 1 + 2^K) + 2*(NL + 3),  NL = 16
lat() { local il=$1 k=$2; echo $(( (64/il + 16/il) * (16*il/4 + 1 + (1<<k)) + 2*(16+3) )); }

for v in $VARIANTS; do
    il=${v#il}; il=${il%%_*}
    m=${v##*_m}
    echo "==== variant $v (IL=$il RNG_MODE=$m) ===="
    YS=$B/synth_$v.ys
    cat > "$YS" <<EOF
# generated by scripts/synth_tpu_variants.sh, revision $REV
read_verilog $RTL
chparam -set IL $il -set RNG_MODE $m -set WEIGHT_INIT "sim/data/weights.hex" -set BIAS_INIT "sim/data/bias.hex" -set INPUT_INIT "sim/data/input.hex" $TOP
synth_gowin -top $TOP -json $B/$v.json
stat
EOF
    # yosys' own -l log (stdout redirection loses the tail, see SKILL lessons).
    yowasp-yosys -l "$LOG/synth_$v.log" -s "$YS" > "$B/synth_${v}_stdout.log" 2>&1 \
        || fail "yosys failed for $v (see $B/synth_${v}_stdout.log)"
    { echo "# cmd: yowasp-yosys -l $LOG/synth_$v.log -s $YS   ($YOSYS_V, revision $REV)"; cat "$YS"; cat "$LOG/synth_$v.log"; } > "$B/tmp.log"
    mv "$B/tmp.log" "$LOG/synth_$v.log"
    grep -q 'End of script' "$LOG/synth_$v.log" || fail "no 'End of script' in synth_$v.log"

    for s in $SEEDS; do
        PL="$LOG/pnr_${v}_s$s.log"
        echo "# cmd: yowasp-nextpnr-himbaechel-gowin --json $B/$v.json --write $B/${v}_pnr.json --device $DEVICE --vopt family=$FAMILY --vopt cst=$CST --freq 27 --report $B/${v}_s${s}_report.json --seed $s --threads 1   ($PNR_V, revision $REV)" > "$PL"
        set +e
        yowasp-nextpnr-himbaechel-gowin --json "$B/$v.json" --write "$B/${v}_pnr.json" \
            --device "$DEVICE" --vopt family=$FAMILY --vopt cst=$CST --freq 27 \
            --report "$B/${v}_s${s}_report.json" --seed "$s" --threads 1 >> "$PL" 2>&1
        rc=$?
        set -e
        echo "PNR_EXIT=$rc" >> "$PL"
        echo "  seed $s: exit $rc :: $(grep 'Max frequency for clock' "$PL" | tail -n 1 | sed 's/^Info: //')"
    done
done

# ---------------------------------------------------------------- report
{
    echo "# SC-TPU synthesis / P&R variant study (task RTL-TPU)"
    echo
    echo "Generated by \`bash scripts/synth_tpu_variants.sh\` on $(date -Is)."
    echo "Input revision: $REV. Tools: $YOSYS_V; $PNR_V."
    echo "Device GW1NR-LV9QN88PC6/I5 (family GW1N-9C), constraint file $CST, --freq 27, --threads 1,"
    echo "seeds: $SEEDS. Top: \`$TOP\` (synthesis-only wrapper: 2-FF reset synchroniser,"
    echo "pseudo-random bus master, read-data signature on the LEDs; ~100 LUT/FF of the totals below)."
    echo
    echo "All numbers are tool results (label SIMULATION in the project sense: synthesis/P&R"
    echo "estimates, not hardware measurements). Utilisation is from the nextpnr 'Device utilisation'"
    echo "block of seed $(echo $SEEDS | awk '{print $1}') (placement does not change cell counts); Fmax is the routed"
    echo "value (last 'Max frequency' line) per seed, worst seed reported. Requirement: Fmax >= 29.7 MHz"
    echo "(27 MHz + 10 % margin)."
    echo
    echo "| Variant | IL | RNG_MODE | LUT4 | ALU | DFF | BSRAM | RAM16SDP4 | MUX2_LUT5..8 | Fmax per seed (MHz) | worst Fmax (MHz) | margin vs 27 MHz | latency cycles K=4 / K=8 / K=10 |"
    echo "|---|---|---|---|---|---|---|---|---|---|---|---|---|"
    for v in $VARIANTS; do
        il=${v#il}; il=${il%%_*}; m=${v##*_m}
        s1=$(echo $SEEDS | awk '{print $1}')
        P1="$LOG/pnr_${v}_s$s1.log"
        u() { grep -E "^Info:[[:space:]]+$1:" "$P1" | sed -n 1p | awk '{print $2}'; }
        mux=0
        for mm in MUX2_LUT5 MUX2_LUT6 MUX2_LUT7 MUX2_LUT8; do
            x=$(grep -E "^Info:[[:space:]]+$mm:" "$P1" | sed -n 1p | awk '{print $2}' | cut -d/ -f1); mux=$((mux + ${x:-0}))
        done
        bs=$(grep -E "^Info:[[:space:]]+(BSRAM|SDPB|SDP):" "$P1" | sed -n 1p | awk '{print $1" "$2}' | sed 's/^Info://')
        fl=""; worst=""
        for s in $SEEDS; do
            f=$(grep 'Max frequency for clock' "$LOG/pnr_${v}_s$s.log" | tail -n 1 | sed -E 's/.*: ([0-9.]+) MHz.*/\1/')
            fl="$fl${fl:+ / }${f:-FAIL}"
            if [ -n "$f" ]; then
                if [ -z "$worst" ] || awk "BEGIN{exit !($f < $worst)}"; then worst=$f; fi
            fi
        done
        margin=$(awk "BEGIN{printf \"%+.1f %%\", ($worst/27-1)*100}")
        echo "| $v | $il | $m | $(u LUT4) | $(u ALU) | $(u DFF) | ${bs:-?} | $(u RAM16SDP4) | $mux | $fl | $worst | $margin | $(lat $il 4) / $(lat $il 8) / $(lat $il 10) |"
    done
    echo
    echo "Latency = cycles from START accepted to DONE (= CYCLES register). Formula of sc_tpu_ctrl.v"
    echo "(CALCULATION): CYCLES = (64/IL + 16/IL) * (NL*IL/4 + 1 + 2^K) + 2*(NL + 3), NL = 16."
    echo "For IL = 8 the formula is confirmed by SIMULATION (tb_sc_tpu D8 and every golden vector:"
    echo "CYCLES register == measured BUSY cycles == formula; logs/tpu/tb_sc_tpu_mode*.log)."
    echo "IL = 4 / 16 latencies are CALCULATION only (not simulated: the golden vectors are defined"
    echo "for IL = 8 only). Time per inference at 27 MHz, K = 8: IL4 $(awk "BEGIN{printf \"%.1f\", $(lat 4 8)/27}") us, IL8 $(awk "BEGIN{printf \"%.1f\", $(lat 8 8)/27}") us, IL16 $(awk "BEGIN{printf \"%.1f\", $(lat 16 8)/27}") us."
    echo
    echo "Logs: logs/tpu/synth_<variant>.log (yosys incl. stat), logs/tpu/pnr_<variant>_s<seed>.log (nextpnr)."
} > "$REP/variants.md"

# Per-variant utilisation block and critical path of the first seed.
for v in $VARIANTS; do
    s1=$(echo $SEEDS | awk '{print $1}')
    P1="$LOG/pnr_${v}_s$s1.log"
    sed -n '/Device utilisation/,/^Info: *$/p' "$P1" | sed -n '1,40p' > "$REP/${v}_utilisation.txt"
    awk '/Critical path report for clock/{f=1; buf=""} f{buf=buf $0 "\n"} /Critical path report for cross-domain|Max frequency for clock/{if(f){last=buf}; f=0} END{printf "%s", last}' "$P1" > "$REP/${v}_critical_path.txt"
done
cat "$REP/variants.md"
echo "SYNTH_TPU DONE (revision $REV)"
