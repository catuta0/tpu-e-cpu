// =============================================================================
// File        : design/rtl/common/smoke_counter.v
// Module      : smoke_counter
// Project     : SC-TPU + RV32I SoC on Sipeed Tang Nano 9K (GW1NR-LV9QN88PC6/I5)
// Task        : ST-FPGA-01 (toolchain smoke test with a known answer)
// Author      : fpga-engineer (Claude Code specialist)
//
// PURPOSE
//   Smallest meaningful design that exercises the complete open-source FPGA
//   route (lint -> simulation -> Yosys synth_gowin -> nextpnr-himbaechel P&R
//   -> gowin_pack bitstream). It is a free-running binary up-counter clocked by
//   the 27 MHz board oscillator; its NUM_LEDS most-significant bits are shown
//   on the board LEDs so that, if the bitstream were ever loaded (NOT done in
//   this project phase), the LEDs would visibly count in binary.
//
// INTERFACES (top-level ports; names match design/constraints/tangnano9k.cst)
//   clk       in   27 MHz board oscillator (crystal oscillator -> FPGA pin 52).
//   btn_s1_n  in   Push-button S1, ACTIVE-LOW (pressed = 0; the CST enables
//                  the internal pull-up so a released button reads 1).
//                  Asynchronous to clk -> passed through a 2-FF synchroniser
//                  and used as a SYNCHRONOUS, active-high internal reset.
//   led_n     out  NUM_LEDS LED drives, ACTIVE-LOW. In the Sipeed Tang Nano 9K
//                  schematic (wiki excerpt LED_Pins.png) each LED anode is tied
//                  to VCCO3_1V8 and its cathode goes to the FPGA pin, so a pin
//                  driven 0 lights the LED and a pin driven 1 turns it off.
//                  led_n[i] = ~count[WIDTH-NUM_LEDS+i], i.e. led_n[NUM_LEDS-1]
//                  shows the counter MSB.
//
// TIMING / LATENCY (cycle-exact; this is what the testbench checks)
//   Let edge #1 be the first rising clk edge after btn_s1_n goes 1 (release).
//     edge #1 : sync_ff1 samples "released" (0); sync_ff2 still 1; the counter
//               sees rst=1 -> count stays 0.
//     edge #2 : sync_ff2 becomes 0, but the counter still sampled rst=1 at this
//               edge (old value of sync_ff2) -> count stays 0.
//     edge #3 : counter sees rst=0 -> count = 1.
//   Hence after N >= 2 rising edges following the release:
//         count = (N - 2) mod 2**WIDTH                       (CALCULATION)
//   e.g. N = 1000 -> count = 998 (0x0003E6).
//   Reset ASSERTION has the same 2-edge latency: the counter keeps counting on
//   the 2 edges following the press and is cleared on the 3rd edge.
//   LED outputs are a pure combinational inversion of count bits (no extra
//   register), so they change in the same cycle as the counter.
//   The critical path is the WIDTH-bit increment (ripple carry through the
//   Gowin ALU carry chain); 24 bits is far below the 37 ns period at 27 MHz.
//
// PARAMETERS
//   WIDTH     Counter width in bits (default 24). With 27 MHz the MSB period is
//             2**24 / 27e6 = 0.621 s (CALCULATION) -> visible LED blinking.
//   NUM_LEDS  Number of MSBs exported to LEDs (default 6 = all board LEDs).
//             Constraint: 1 <= NUM_LEDS <= WIDTH (checked in simulation below).
//
// ASSUMPTIONS
//   * GW1NR-9 registers power up to their INIT value (0 unless stated). The
//     synchroniser is initialised to "reset asserted" (2'b11) so that, after
//     FPGA configuration, the counter is held in reset until the synchroniser
//     has observed the (released) button for 2 clock edges. Yosys maps the
//     initial value onto the Gowin DFF INIT attribute (DFFS/DFFSE cells).
//   * Button contact bounce is irrelevant here: every bounce simply re-asserts
//     the reset, and the counter restarts from 0 after the final release.
//
// REQUIREMENT REFERENCES
//   Toolchain smoke test only (ST-FPGA-01); no product requirement IDs yet.
//   Conventions from .claude/skills/rtl-gowin-flow/SKILL.md: Verilog-2005,
//   `default_nettype none, synchronous active-high internal reset `rst`
//   generated by a synchroniser in the top level, single 27 MHz clock domain.
// =============================================================================

module smoke_counter #(
    parameter integer WIDTH    = 24,  // counter width (bits)
    parameter integer NUM_LEDS = 6    // number of MSBs shown on LEDs
) (
    input  wire                clk,       // 27 MHz board clock
    input  wire                btn_s1_n,  // S1 push-button, active-low, async
    output wire [NUM_LEDS-1:0] led_n      // LEDs, active-low
);

    // -------------------------------------------------------------------------
    // Reset synchroniser (2 flip-flops)
    // -------------------------------------------------------------------------
    // WHY: btn_s1_n is a mechanical button, fully asynchronous to clk. Using it
    // directly as a reset could violate setup/hold of the counter flip-flops
    // and make different counter bits leave reset in different cycles
    // (metastability / reset-release skew). Two flip-flops in series give the
    // first stage a full clock period to resolve metastability before the
    // value is used. The button is inverted at the INPUT of the chain, so the
    // chain carries the active-high "reset requested" level.
    //
    // Initial value 2'b11 = "reset asserted" at power-up / after configuration
    // (see ASSUMPTIONS in the header).
    reg sync_ff1 = 1'b1;  // first stage: may go metastable, never used directly
    reg sync_ff2 = 1'b1;  // second stage: clean synchronous reset

    always @(posedge clk) begin
        sync_ff1 <= ~btn_s1_n;  // pressed (0) -> request reset (1)
        sync_ff2 <= sync_ff1;   // re-time; adds the 2nd edge of latency
    end

    // Internal synchronous, active-high reset (project convention name: rst).
    wire rst = sync_ff2;

    // -------------------------------------------------------------------------
    // Free-running counter
    // -------------------------------------------------------------------------
    // WHY synchronous reset: matches the project convention (single clock
    // domain, reset sampled like any other data input) and lets Yosys use the
    // Gowin DFFR/DFFRE-style synchronous-reset flip-flops (no async reset net).
    // The counter wraps naturally from 2**WIDTH-1 to 0 because the addition is
    // truncated to WIDTH bits (modulo 2**WIDTH arithmetic) - no compare logic.
    reg [WIDTH-1:0] count = {WIDTH{1'b0}};

    always @(posedge clk) begin
        if (rst)
            count <= {WIDTH{1'b0}};                     // held / cleared in reset
        else
            count <= count + {{(WIDTH-1){1'b0}}, 1'b1}; // +1, wraps mod 2**WIDTH
    end

    // -------------------------------------------------------------------------
    // LED outputs
    // -------------------------------------------------------------------------
    // Take the NUM_LEDS most-significant counter bits and invert them because
    // the board LEDs are active-low (pin 0 = LED on). Bit mapping:
    //   led_n[NUM_LEDS-1] <- ~count[WIDTH-1]   (MSB, slowest blink)
    //   led_n[0]          <- ~count[WIDTH-NUM_LEDS]  (fastest of the shown bits)
    assign led_n = ~count[WIDTH-1 -: NUM_LEDS];

    // -------------------------------------------------------------------------
    // Elaboration-time parameter check (simulation only; ignored by synthesis)
    // -------------------------------------------------------------------------
    // synthesis translate_off
    initial begin
        if (NUM_LEDS < 1 || NUM_LEDS > WIDTH) begin
            $display("ERROR: smoke_counter: need 1 <= NUM_LEDS (%0d) <= WIDTH (%0d)",
                     NUM_LEDS, WIDTH);
            $finish;
        end
    end
    // synthesis translate_on

endmodule

`default_nettype wire
